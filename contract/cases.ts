export interface ContractCase {
  readonly name: string
  readonly method?: string
  readonly path: string
  readonly headers?: Readonly<Record<string, string>>
  readonly body?: string
  /** En-têtes comparés en plus de Content-Type. */
  readonly compareHeaders?: readonly string[]
  /** Écart assumé et documenté (README, CLAUDE.md) : signalé sans faire échouer. */
  readonly knownDifference?: string
}

const JSON_ACCEPT = { Accept: 'application/json' }
const ANY_ACCEPT = { Accept: '*/*' }
const JSON_BODY = { 'Content-Type': 'application/json', Accept: 'application/json' }
const VALID = '"email":"camille@example.fr","message":"Bonjour, je souhaite un devis."'
const CORS_HEADERS = [
  'access-control-allow-origin',
  'access-control-allow-methods',
  'access-control-allow-headers',
  'access-control-max-age',
]

const get = (path: string, headers: Record<string, string> = JSON_ACCEPT): ContractCase => ({
  name: `GET ${path}${headers === JSON_ACCEPT ? '' : ` ${JSON.stringify(headers)}`}`,
  path,
  headers,
})

const post = (
  name: string,
  body: string,
  headers: Record<string, string> = JSON_BODY,
  extra: Partial<ContractCase> = {},
): ContractCase => ({
  name: `POST contact : ${name}`,
  method: 'POST',
  path: '/api/contact_messages',
  headers,
  body,
  compareHeaders: ['location', 'content-location'],
  ...extra,
})

